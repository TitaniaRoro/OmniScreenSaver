export function normalizeLanguage(language) {
  return String(language || "en").toLowerCase().startsWith("bn") ? "bn" : "en";
}

export function translate(language, key, values = {}) {
  const dict = dictionaries[normalizeLanguage(language)];
  const fallback = dictionaries.en[key] ?? key;
  return String(dict[key] ?? fallback).replace(/\{(\w+)\}/g, (_, name) => String(values[name] ?? ""));
}

export function applyTranslations(language, root = document) {
  const lang = normalizeLanguage(language);
  root.documentElement.lang = lang === "bn" ? "bn" : "en";
  root.documentElement.dir = "ltr";
  root.querySelectorAll("[data-i18n]").forEach(element => {
    const key = element.dataset.i18n;
    element.textContent = translate(lang, key);
  });
  root.querySelectorAll("[data-i18n-placeholder]").forEach(element => {
    element.setAttribute("placeholder", translate(lang, element.dataset.i18nPlaceholder));
  });
  root.querySelectorAll("[data-i18n-aria]").forEach(element => {
    element.setAttribute("aria-label", translate(lang, element.dataset.i18nAria));
  });
  const languageButton = root.getElementById("languageToggle");
  if (languageButton) languageButton.textContent = lang === "bn" ? "English" : "বাংলা";
  return lang;
}

export function getModeText(language, mode) {
  return {
    title: translate(language, mode.nameKey),
    description: translate(language, mode.descriptionKey)
  };
}

